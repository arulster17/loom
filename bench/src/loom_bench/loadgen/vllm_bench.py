"""`vllm bench serve` (vLLM v0.30.0) as a Loom load generator.

Flags and result fields are those of `vllm/benchmarks/serve.py` and
`vllm/benchmarks/datasets/datasets.py` at the v0.30.0 tag.

Workloads: `synthetic` -> the `random` dataset and `shared_prefix` ->
`prefix_repetition` (prompts generated by vLLM); every other kind replays the
Loom requests through a `custom` JSONL dataset, unshuffled and without the
client-side chat template, so the measured prompts are the native generator's.
Arrivals: Poisson, gamma (`--burstiness`) and constant (`--burstiness inf`).
"""

from __future__ import annotations

import json
import math
from collections.abc import Sequence
from pathlib import Path

from loom_bench.client.openai_stream import API_PATHS
from loom_bench.loadgen.arrivals import ConstantArrivals, GammaArrivals, PoissonArrivals
from loom_bench.loadgen.base import RunResult
from loom_bench.loadgen.external import (
    ExternalLoadGenerator,
    ToolRun,
    UnsupportedByTool,
    ignore_eos,
    read_result,
    result_from_arrays,
    shared_prefix_lengths,
    single_user_prompt,
    split_base_url,
    tool_summary,
    write_jsonl,
)
from loom_bench.records import LoadMode
from loom_bench.workloads.profiles import SharedPrefixProfile, SyntheticProfile

NAME = "vllm_bench"

_BACKENDS = {"completions": "openai", "chat": "openai-chat"}
_SUMMARY_KEYS = (
    "duration",
    "completed",
    "failed",
    "request_throughput",
    "output_throughput",
    "total_token_throughput",
    "max_concurrent_requests",
)


class VllmBench:
    name = NAME
    result_file = "result.json"

    def __init__(self, executable: Sequence[str] = ("vllm",)) -> None:
        self.executable = list(executable)

    def build_argv(self, run: ToolRun, result_path: Path) -> list[str]:
        root, prefix = split_base_url(run.job.base_url)
        endpoint = run.profile.endpoint
        argv = [
            *self.executable, "bench", "serve",
            "--backend", _BACKENDS[endpoint],
            "--base-url", root,
            "--endpoint", prefix + API_PATHS[endpoint],
            "--model", run.job.served_model,
        ]  # fmt: skip
        if run.tokenizer:
            argv += ["--tokenizer", run.tokenizer]
        argv += [
            "--num-prompts", str(run.num_prompts),
            "--seed", str(run.job.seed),
            "--num-warmups", str(run.warmup_requests),
            *self._load_args(run),
            *self._dataset_args(run),
        ]  # fmt: skip
        if ignore_eos(run.profile):
            argv.append("--ignore-eos")
        argv += ["--temperature", str(float(run.profile.temperature))]
        if run.job.extra_body:
            argv += ["--extra-body", json.dumps(dict(run.job.extra_body), sort_keys=True)]
        argv += [
            "--percentile-metrics", "ttft,tpot,itl,e2el",
            "--metric-percentiles", "50,90,95,99",
            "--save-result", "--save-detailed",
            "--result-filename", str(result_path),
            "--disable-tqdm",
        ]  # fmt: skip
        return argv

    def parse(self, run: ToolRun, result_path: Path) -> RunResult:
        data = read_result(result_path, NAME)
        return result_from_arrays(
            run, data, tool=NAME, meta={"tool_summary": tool_summary(data, _SUMMARY_KEYS)}
        )

    def _load_args(self, run: ToolRun) -> list[str]:
        if run.mode is LoadMode.CLOSED_LOOP:
            return ["--request-rate", "inf", "--max-concurrency", str(run.concurrency)]
        arrival = run.ctx.arrival
        match arrival:
            case PoissonArrivals():
                rate, burstiness = arrival.rate, 1.0
            case GammaArrivals():
                rate, burstiness = arrival.rate, arrival.burstiness
            case ConstantArrivals():
                rate, burstiness = arrival.rate, math.inf
            case _:
                kind = getattr(arrival, "kind", None)
                raise UnsupportedByTool(
                    f"vllm bench serve generates poisson, gamma or constant arrivals, not "
                    f"{kind}; use the native generator"
                )
        # --max-concurrency mirrors the native max_inflight cap; waits show up as queue_times.
        return [
            "--request-rate", str(float(rate)),
            "--burstiness", str(float(burstiness)),
            "--max-concurrency", str(run.concurrency),
        ]  # fmt: skip

    def _dataset_args(self, run: ToolRun) -> list[str]:
        p = run.profile
        if isinstance(p, SyntheticProfile):
            if not p.ignore_eos:
                raise UnsupportedByTool(
                    "vllm bench serve always ignores EOS on its random dataset; "
                    "set ignore_eos: true or use the native generator"
                )
            return [
                "--dataset-name", "random",
                "--random-input-len", str(p.input_len),
                "--random-output-len", str(p.output_len),
                "--random-range-ratio", str(p.range_ratio),
            ]  # fmt: skip
        if isinstance(p, SharedPrefixProfile):
            prefix, suffix, output = shared_prefix_lengths(p, "vllm bench serve")
            return [
                "--dataset-name", "prefix_repetition",
                "--prefix-repetition-prefix-len", str(prefix),
                "--prefix-repetition-suffix-len", str(suffix),
                "--prefix-repetition-num-prefixes", str(p.num_prefix_groups),
                "--prefix-repetition-output-len", str(output),
            ]  # fmt: skip
        write_custom_dataset(run)
        return [
            "--dataset-name", "custom",
            "--dataset-path", str(run.dataset_path),
            "--custom-output-len", "-1",
            "--skip-chat-template",
            "--disable-shuffle",
            "--no-oversample",
        ]  # fmt: skip


def write_custom_dataset(run: ToolRun) -> None:
    """vLLM `custom` rows: ``{"prompt": str, "output_tokens": int}``; with
    `--custom-output-len -1` each row's `output_tokens` becomes `max_tokens`."""
    rows = [
        {
            "prompt": single_user_prompt(req, "vllm bench serve"),
            "output_tokens": req.payload["max_tokens"],
        }
        for req in run.requests
    ]
    write_jsonl(run.dataset_path, rows)


def generator() -> ExternalLoadGenerator:
    return ExternalLoadGenerator(VllmBench())
