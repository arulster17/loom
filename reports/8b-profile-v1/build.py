"""Rebuild this report's breakdowns and tables from the stored traces (free, no GPU).

    uv run python reports/8b-profile-v1/build.py \
        /path/to/results/14d959e5-5a13-4939-a56d-71a8d87d9d2a

1. Every profile window's trace (`profiles/<run id>/trace.tar.gz`) goes through
   `loom_bench.profile.trace.analyze_path` (what `bench profile analyze` runs) and lands in
   `breakdowns/<cell>_<workload>_<load>_<run id>.json` with the window's capture facts.
2. `tables.md` is written from those JSON files: one row per window, pure-decode steps
   by batch, steps carrying prefill, and the per-layer GEMM bandwidth of the B=1 windows.

Floors use the same constants as `bench roofline` (L40S 864 GB/s, 362 / 733 TFLOP/s;
Qwen3-8B byte accounting from loom_bench.profile.arch).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from loom_bench.profile.trace import analyze_path

HERE = Path(__file__).parent
OUT = HERE / "breakdowns"
CATS = ("gemm", "attention", "quant", "sampling", "memcpy", "other", "idle")
HBM = 864e9
PEAK = {"bf16": 362e12, "fp8-kv8": 733e12}
WEIGHT_BYTES = {"bf16": 15.14e9, "fp8-kv8": 8.19e9}  # linear layers + LM head, per step
# Prefill: 2 FLOPs per linear-layer parameter per prompt token; the LM head runs only
# for the sampled position, so it is left out (6.95 B of the 7.57 B step parameters).
PREFILL_PARAMS = 6.95e9


def build(exp: Path) -> None:
    OUT.mkdir(exist_ok=True)
    for w in sorted((exp / "profiles").glob("*/window.json")):
        doc = json.loads(w.read_text())
        res = analyze_path(w.parent / "trace.tar.gz")
        keep = ("run_id", "cell", "workload", "load_value", "client_latency", "capture")
        name = f"{doc['cell']}_{doc['workload']}_{doc['load_value']:g}_{doc['run_id'][:8]}.json"
        body = {"window": {k: doc[k] for k in keep}, "trace_bytes": doc["trace_bytes"]}
        (OUT / name).write_text(json.dumps({**body, **res.as_dict()}, indent=1))


def load() -> list[dict]:
    rows = [json.loads(p.read_text()) for p in sorted(OUT.glob("*.json"))]
    order = {"fixed-1k-1k": 0, "chat-sharegpt": 1}
    return sorted(
        rows,
        key=lambda d: (
            d["window"]["cell"] != "bf16",
            order[d["window"]["workload"]],
            d["window"]["load_value"],
        ),
    )


def fmt(x: float, nd: int = 2) -> str:
    return f"{x:.{nd}f}"


def tables(rows: list[dict]) -> str:
    out = ["# Profile tables (generated by build.py; do not edit)", ""]
    out += [
        "## Windows",
        "",
        "Each window: 20 s of the profiler recording every engine step under the same load "
        "as the measured runs. ITL = the client's inter-token gap inside the window and in "
        "the 22 s just before it (same job). Steps from vLLM's step annotations.",
        "",
        "| Cell | Workload | Load | Run | Steps | Trace MB | Flush s | ITL p50 profiled / before (ms) | Slowdown |",  # noqa: E501
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for d in rows:
        w, r = d["window"], d["ranks"][0]
        lat, cap = w["client_latency"], w["capture"]
        out.append(
            f"| {w['cell']} | {w['workload']} | {w['load_value']:g} | {w['run_id'][:8]} | "
            f"{r['steps']} | {d['trace_bytes'] / 1e6:.1f} | "
            f"{cap['stopped_s'] - cap['stop_s']:.0f} | "
            f"{lat['profiled']['itl_p50_ms']:.2f} / {lat['before']['itl_p50_ms']:.2f} | "
            f"{lat.get('profiler_slowdown', float('nan')):.3f} |"
        )
    out += [
        "",
        "## Pure-decode steps by batch",
        "",
        "Milliseconds per step, from one step's start to the next (the LM head, sampling and "
        "any GPU wait are inside). Batches with at least 5% of a window's decode steps; "
        "`n` = steps. Weight floor: bf16 17.52 ms, fp8 9.48 ms.",
        "",
        "| Cell | Workload | Load | Batch | n | Step p50 | "
        + " | ".join(c.capitalize() for c in CATS)
        + " |",
        "|---|---|---|---|---|---|" + "---|" * len(CATS),
    ]
    for d in rows:
        w, r = d["window"], d["ranks"][0]
        dec = [g for g in r["step_shapes"] if g["kind"] == "decode"]
        total = sum(g["steps"] for g in dec) or 1
        for g in dec:
            if g["steps"] < 0.05 * total:
                continue
            out.append(
                f"| {w['cell']} | {w['workload']} | {w['load_value']:g} | {g['batch']} | "
                f"{g['steps']} | {fmt(g['step_ms_p50'])} | "
                + " | ".join(fmt(g["category_ms"][c]) for c in CATS)
                + " |"
            )
    out += [
        "",
        "## Steps carrying prefill",
        "",
        "`Share` = the window's time spent in these steps. Prefill cost per prompt token = "
        "(mean mixed step - median decode step of the window) / prefill tokens; its compute "
        "floor is 2 x 6.95 GFLOP / peak (bf16 38.4 us, fp8 19.0 us; the LM head runs only "
        "for sampled positions). The subtraction leaves attention over the prompt in, so "
        "this is an upper bound.",
        "",
        "| Cell | Workload | Load | Steps | Share of window | Prefill tokens (mean) | Step mean | "
        + " | ".join(c.capitalize() for c in CATS)
        + " | us / prompt token | % of compute peak |",
        "|---|---|---|---|---|---|---|" + "---|" * len(CATS) + "---|---|",
    ]
    for d in rows:
        w, r = d["window"], d["ranks"][0]
        mixed = [g for g in r["step_shapes"] if g["kind"] == "mixed"]
        dec = [g for g in r["step_shapes"] if g["kind"] == "decode"]
        if not mixed or not dec:
            continue
        g = mixed[0]
        share = g["steps"] * g["step_ms_mean"] / r["window_ms"]
        heavy = max(dec, key=lambda x: x["steps"])
        per_tok = (g["step_ms_mean"] - heavy["step_ms_p50"]) / g["prefill_tokens_mean"] * 1000
        floor = 2 * PREFILL_PARAMS / PEAK[w["cell"]] * 1e6
        out.append(
            f"| {w['cell']} | {w['workload']} | {w['load_value']:g} | {g['steps']} | "
            f"{100 * share:.0f}% | {g['prefill_tokens_mean']:.0f} | {fmt(g['step_ms_mean'], 1)} | "
            + " | ".join(fmt(g["category_ms"][c]) for c in CATS)
            + f" | {per_tok:.0f} | {100 * floor / per_tok:.0f}% |"
        )
    out += [
        "",
        "## GEMM bandwidth at batch 1 (fixed-1k-1k, concurrency 1)",
        "",
        "Bytes every step must read for its linear layers and LM head, over the measured GEMM "
        "time per step.",
        "",
        "| Cell | GEMM ms / step | Weight bytes | Achieved GB/s | % of 864 GB/s |",
        "|---|---|---|---|---|",
    ]
    for d in rows:
        w, r = d["window"], d["ranks"][0]
        if w["workload"] != "fixed-1k-1k" or w["load_value"] != 1:
            continue
        dec = next(g for g in r["step_shapes"] if g["kind"] == "decode" and g["batch"] == 1)
        gemm = dec["category_ms"]["gemm"]
        gbs = WEIGHT_BYTES[w["cell"]] / (gemm / 1000) / 1e9
        out.append(
            f"| {w['cell']} | {fmt(gemm)} | {WEIGHT_BYTES[w['cell']] / 1e9:.2f} GB | "
            f"{gbs:.0f} | {100 * gbs * 1e9 / HBM:.0f}% |"
        )
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) > 1:
        build(Path(sys.argv[1]))
    (HERE / "tables.md").write_text(tables(load()))
    print(f"wrote {HERE / 'tables.md'}")
